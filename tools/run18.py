fails = []
def check(cond, msg):
    print(('OK   ' if cond else 'FAIL ') + msg)
    if not cond: fails.append(msg)

def errs_of(page):
    return [m for m in page._errs if 'fonts.gstatic' not in m and 'favicon' not in m]

def open_page(b, path, dark=False, w=1280, h=900, mobile=False):
    ctx = b.new_context(has_touch=True, is_mobile=True, viewport={'width': w, 'height': h}, device_scale_factor=2) if mobile else b.new_context()
    page = ctx.new_page()
    page._errs = []
    page.on('console', lambda m: page._errs.append(m.text) if m.type == 'error' else None)
    page.on('pageerror', lambda e: page._errs.append(str(e)))
    page.emulate_media(color_scheme='dark' if dark else 'light')
    page.set_viewport_size({'width': w, 'height': h})
    page.goto(BASE + path)
    page.wait_for_selector('.rows .row', timeout=8000)
    page.wait_for_timeout(300)
    return page

def no_hscroll(page):
    return page.evaluate('document.documentElement.scrollWidth <= window.innerWidth + 1')

